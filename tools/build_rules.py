MANUAL = {'type': 'manual'}
XP_DMG = 'очки за отнятые жизни'


def sp(caster, level, name, cost, xp, description, effect=MANUAL, costFormula=None, xpFormula=None,
       target=None, duration=None, luck=None):
    d = {'id': f'{caster}-{slug(name)}', 'caster': caster, 'level': level, 'name': name, 'cost': cost}
    if costFormula:
        d['costFormula'] = costFormula
    if target:
        d['target'] = target
    if duration:
        d['duration'] = duration
    if luck is not None:
        d['luck'] = luck
    d['xp'] = xp
    if xpFormula:
        d['xpFormula'] = xpFormula
    d['description'] = description
    d['effect'] = effect
    return d


def dmg(dice, targets='one', perLevel=False, max=None):
    e = {'type': 'damage', 'dice': dice, 'targets': targets}
    if perLevel:
        e['perLevel'] = True
    if max is not None:
        e['max'] = max
    return e


def buff(stat, amount, scope, duration):
    return {'type': 'buff', 'stat': stat, 'amount': amount, 'scope': scope, 'duration': duration}


def debuff(stat, amount, scope, duration):
    return {'type': 'debuff', 'stat': stat, 'amount': amount, 'scope': scope, 'duration': duration}


def summon(name, **kw):
    e = {'type': 'summon', 'name': name}
    e.update(kw)
    return e


