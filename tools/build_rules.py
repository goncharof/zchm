STAT = {'с': 'strength', 'л': 'dexterity', 'м': 'accuracy', 'у': 'luck', 'з': 'defense'}


def levels(xp, lives, bonuses=None, mana=None, special=None):
    rows = []
    for i in range(13):
        row = {'level': i, 'xp': xp[i], 'lives': lives[i]}
        if mana:
            row['mana'] = mana[i]
        if bonuses and i >= 1 and i <= len(bonuses):
            b = bonuses[i - 1]
            if b:
                row['bonus'] = {STAT[b[0]]: int(b[1:])}
        if special and i == 12:
            row['special'] = special
        rows.append(row)
    return rows


